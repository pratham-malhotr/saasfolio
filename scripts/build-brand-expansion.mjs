import fs from "node:fs";
import { loadCatalogModule } from "./lib/load-catalog.mjs";
const categories = {
  "ai-tools": "Artificial Intelligence", marketing: "Growth & Marketing", "crm-sales": "CRM & Sales Automation",
  "dev-tools": "Developer & API Tools", design: "Design & Creative Systems", analytics: "Analytics & Product Telemetry",
  hosting: "Cloud Hosting & Edge Infra", finance: "Fintech, Billing & Invoicing", productivity: "Productivity & Knowledge Hubs",
  security: "Cybersecurity & Compliance", ecommerce: "E-Commerce & Checkout Engines", "project-management": "Project & Sprint Management",
};
const outputPath = new URL("../lib/data/expanded-tools.json", import.meta.url);
const existing = new Set(JSON.parse(fs.readFileSync(outputPath, "utf8")).map(tool => tool.slug));
const rows = fs.readFileSync(new URL("../lib/data/brand-expansion.txt", import.meta.url), "utf8").split(/\r?\n/).filter(l => l && !l.startsWith("#"));
const tools = rows.map(line => {
  const [name, slug, categorySlug, pricingUrl, description, features, reviewedAt = "2026-10-21", pricingModel = "Paid"] = line.split("|");
  if (!existing.has(slug) && line.split("|").length < 8) throw new Error(`${slug}: new brands require an actual review date and pricing model`);
  if (!categories[categorySlug]) throw new Error(`Unknown category: ${categorySlug}`);
  if (!["Free Trial", "Freemium", "Paid", "Open Source"].includes(pricingModel)) throw new Error(`Unknown pricing model: ${pricingModel}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(reviewedAt) || !Number.isFinite(Date.parse(reviewedAt)) || Date.parse(reviewedAt) > Date.now()) throw new Error(`Invalid review date: ${slug}`);
  return {
    id: `tool-${slug}`, name, slug, tagline: description, description,
    longDescription: `${description}\n\nIts product areas include ${features.split(";").join(", ").toLowerCase()}. Compare these capabilities with your team's workflow, integrations, and budget.\n\nFollow the official pricing link for current plans, usage allowances, and billing terms. SaaSFolio does not assign a customer rating or claim a discount without a recorded source.`,
    category: categories[categorySlug], categorySlug, website: new URL(pricingUrl).origin, pricingUrl, sourceUrl: pricingUrl,
    logoLetter: name.replace(/[^A-Za-z0-9]/g, "").slice(0, 2).toUpperCase(), rating: 0, reviewCount: 0,
    pricingStart: 0, pricingModel, pricingVerified: false, verified: false,
    bestFor: description, keyFeatures: features.split(";"), pros: [], cons: [], pricingPlans: [], alternatives: [], reviews: [], dealsCount: 0,
    tier: "mid-tier", updatedAt: `${reviewedAt}T00:00:00.000Z`,
  };
});
if (new Set(tools.map(t => t.slug)).size !== tools.length) throw new Error("Duplicate expansion slug");

// The complete entry modules stay available to server-rendered guides and this
// generator. Interactive catalogs consume only their compact reviewed profile
// projection, avoiding a runtime import of every guide's prose into client JS.
// Loading this source does not depend on the generated file, so regeneration
// also works from a clean checkout before that output exists.
const { NEW_REVIEWED_BRAND_COPY } = loadCatalogModule("lib/data/discount-brand-expansion.ts");
const reviewedProfiles = Object.fromEntries(Object.entries(NEW_REVIEWED_BRAND_COPY)
  .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
const profileSource = `// Generated by npm run catalog:expand from the dated discount guide entries.
// Keep browser catalog imports independent of the complete editorial guides.
import type { DetailedTool } from "@/lib/types";

export const DISCOUNT_REVIEWED_PROFILE_COPY = ${JSON.stringify(reviewedProfiles, null, 2)} satisfies Record<string, Pick<DetailedTool,
  "name" | "website" | "pricingUrl" | "updatedAt" | "pricingModel" | "tagline" | "description" | "longDescription" | "keyFeatures">>;
`;
fs.writeFileSync(new URL("../lib/data/expanded-tools.json", import.meta.url), `${JSON.stringify(tools, null, 2)}\n`);
fs.writeFileSync(new URL("../lib/data/discount-reviewed-profile-copy.ts", import.meta.url), profileSource);
console.log(`Generated ${tools.length} additional brand profiles`);
console.log(`Generated ${Object.keys(reviewedProfiles).length} compact reviewed discount profiles`);
